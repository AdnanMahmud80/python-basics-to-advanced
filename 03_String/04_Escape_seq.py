a = "Hello \n World!"
print("a=",a) # prints the string with a newline character

b = "Hello \t World!"
print("b=",b) # prints the string with a tab character

c = "Hello \"World\"!"
print("c=",c) # prints the string with double quotes

d = "Hello \'World\'!"
print("d=",d) # prints the string with single quotes

e = "Hello \; World!"
print("e=",e) # prints the string with a backslash

f = "Hello \r World!"
print("f=",f) # prints the string with a carriage return

g = "Hello \b World!"
print("g=",g) # prints the string with a backspace

h = "Hello \f World!"
print("h=",h) # prints the string with a form feed

i = "Hello \v World!"
print("i=",i) # prints the string with a vertical tab

j = "Hello \a World!"
print("j=",j) # prints the string with a bell/alert sound

k = "Hello \0 World!"
print("k=",k) # prints the string with a null character