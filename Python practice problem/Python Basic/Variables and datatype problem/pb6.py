# Problem 6: Calculate Area and Perimeter
# Take the length and width of a rectangle as input.
# Calculate and print its area and perimeter.
# Area = length * width
# Perimeter = 2 * (length + width)
a = float (input("Enter Length:"))
b = float (input("Enter Width:"))
Area = a * b
perimeter = 2*(a*b)
print("Area:",Area)
print("Perimeter: ",perimeter)
