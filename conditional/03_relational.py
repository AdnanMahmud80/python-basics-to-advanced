# Relational (comparison) operators compare two values and return True or False.
#
# ==  equal to
# !=  not equal to
# >   greater than
# <   less than
# >=  greater than or equal to
# <=  less than or equal to
#
# Example:
first_number = 10
second_number = 5

print(first_number == second_number)  # False
print(first_number != second_number)  # True
print(first_number > second_number)   # True
print(first_number < second_number)   # False
print(first_number >= 10)             # True
print(second_number <= 5)             # True

# Note: = assigns a value; == checks whether two values are equal.
